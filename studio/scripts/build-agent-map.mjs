// Builds studio/app/agents.json + docs/AGENT_MAP.md from the repo's agent frontmatter.
// Usage: node studio/scripts/build-agent-map.mjs   (run from repo root or anywhere)
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
const here = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const DIVINFO = JSON.parse(fs.readFileSync(path.join(root,'divisions.json'),'utf8')).divisions;
const DIVS = Object.keys(DIVINFO);
const RUNBOOKS = JSON.parse(fs.readFileSync(path.join(root,'strategy/runbooks.json'),'utf8')).runbooks;
// Pipeline stage -> the agent files the orchestrator assigns (must exist on disk; checked below).
export const ROLES = {
  strategy: ['marketing/marketing-social-media-strategist.md','marketing/marketing-growth-hacker.md'],
  brand: ['design/design-brand-guardian.md'],
  draft: {
    x: 'marketing/marketing-twitter-engager.md',
    instagram: 'marketing/marketing-instagram-curator.md',
    tiktok: 'marketing/marketing-tiktok-strategist.md',
    linkedin: 'marketing/marketing-linkedin-content-creator.md',
    facebook: 'marketing/marketing-content-creator.md',
    youtube_shorts: 'marketing/marketing-short-video-editing-coach.md'
  },
  visuals: ['design/design-visual-storyteller.md','design/design-image-prompt-engineer.md','marketing/marketing-carousel-growth-engine.md'],
  seo: ['marketing/marketing-seo-specialist.md'],
  qa: ['testing/testing-reality-checker.md','design/design-inclusive-visuals-specialist.md'],
  factcheck: ['testing/testing-evidence-collector.md'],
  publish: ['marketing/marketing-multi-platform-publisher.md'],
  analytics: ['marketing/marketing-x-twitter-intelligence-analyst.md'],
  replies: ['marketing/marketing-twitter-engager.md','support/support-support-responder.md'],
  leads: ['sales/sales-offer-lead-gen-strategist.md','sales/sales-outbound-strategist.md']
};
function fm(txt){ const m = txt.match(/^---\n([\s\S]*?)\n---/); if(!m) return null; const o={};
  for (const l of m[1].split('\n')) { const i=l.indexOf(':'); if(i>0) o[l.slice(0,i).trim()] = l.slice(i+1).trim().replace(/^"|"$/g,''); } return o; }
const agents = [];
// Definition (matches the agency-agents digest): every *.md file anywhere under a division directory
// (recursive — e.g. game-development/unity/*.md) whose frontmatter has a `name:` field. Files without it are skipped and listed.
const skipped = [];
function walk(dir){ return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=> e.isDirectory() ? walk(path.join(dir,e.name)) : e.name.endsWith('.md') ? [path.join(dir,e.name)] : []).sort(); }
for (const d of DIVS) { const dir = path.join(root,d); if(!fs.existsSync(dir)) continue;
  for (const full of walk(dir)) { const rel = path.relative(root, full).split(path.sep).join('/'); const f = path.basename(full);
    const meta = fm(fs.readFileSync(full,'utf8')); if(!meta||!meta.name) { skipped.push(rel); continue; }
    agents.push({ slug:f.replace(/\.md$/,''), file:rel, division:d, name:meta.name, emoji:meta.emoji||'', description:(meta.description||'').slice(0,240) });
  } }
const flat = Object.values(ROLES).flatMap(v=>Array.isArray(v)?v:Object.values(v));
const missing = flat.filter(f=>!fs.existsSync(path.join(root,f)));
const slugs=new Set(agents.map(a=>a.slug)); const badRb = RUNBOOKS.flatMap(r=>r.roster.flatMap(g=>g.agents)).filter(x=>!slugs.has(x));
if (badRb.length) console.warn('runbook slugs not found:', [...new Set(badRb)]);
if (missing.length) { console.error('MISSING role files:', missing); process.exit(1); }
const byFile = Object.fromEntries(agents.map(a=>[a.file,a]));
const nameOf = f => (byFile[f]||{}).name || f;
const out = { generated: new Date().toISOString(), definition: 'All *.md under division dirs (recursive) with frontmatter name:', skipped, source: 'msitarzewski/agency-agents (MIT)', count: agents.length, roles: ROLES,
  divisions: DIVINFO, runbooks: RUNBOOKS.map(r=>({slug:r.slug,title:r.title,mode:r.mode,duration:r.duration,summary:r.summary,agents:[...new Set(r.roster.flatMap(g=>g.agents))]})), roleNames: Object.fromEntries(Object.entries(ROLES).map(([k,v])=>[k, Array.isArray(v)? v.map(nameOf) : Object.fromEntries(Object.entries(v).map(([p,f])=>[p,nameOf(f)]))])), agents };
fs.writeFileSync(path.join(here,'../app/agents.json'), JSON.stringify(out,null,1));
let md = `# Agent map (generated by scripts/build-agent-map.mjs)\n\n${agents.length} agents scanned in: ${DIVS.join(', ')}. Source: msitarzewski/agency-agents (MIT).\n\n## Pipeline role assignment\n\n| Stage | Agent(s) | File(s) |\n|---|---|---|\n`;
for (const [k,v] of Object.entries(ROLES)) { const fs_ = Array.isArray(v)? v : Object.entries(v).map(([p,f])=>f);
  const labels = Array.isArray(v)? v.map(nameOf) : Object.entries(v).map(([p,f])=>`${p}: ${nameOf(f)}`);
  md += `| ${k} | ${labels.join('<br>')} | ${fs_.map(f=>'`'+f+'`').join('<br>')} |\n`; }
md += `\n## All scanned agents by division\n`;
for (const d of DIVS) { const list = agents.filter(a=>a.division===d); if(!list.length) continue;
  md += `\n### ${d} (${list.length})\n\n` + list.map(a=>`- **${a.name}** (\`${a.file}\`): ${a.description.replace(/\|/g,'/')}`).join('\n') + '\n'; }
fs.writeFileSync(path.join(here,'../docs/AGENT_MAP.md'), md);
console.log(`agents=${agents.length} skipped_no_name=${skipped.length} roles_ok missing=0`); if (skipped.length) console.log('skipped:', skipped.join(', '));
